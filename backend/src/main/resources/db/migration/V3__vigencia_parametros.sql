ALTER TABLE parametro ADD COLUMN origem VARCHAR(200);
ALTER TABLE parametro ADD COLUMN valor_documento NUMERIC(15, 4);

-- Valores por vigência (mês de início, AAAA-MM)
CREATE TABLE parametro_vigencia (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave          VARCHAR(60)    NOT NULL REFERENCES parametro (chave),
    valor          NUMERIC(15, 4) NOT NULL,
    vigente_desde  VARCHAR(7)     NOT NULL,
    registrado_em  TIMESTAMP      NOT NULL,
    registrado_por VARCHAR(200),
    CONSTRAINT uk_parametro_vigencia UNIQUE (chave, vigente_desde)
);

