-- Schema inicial: Contas a Receber, Pós-venda e Comissão de Vendedor

CREATE TABLE usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keycloak_id   VARCHAR(64)  NOT NULL UNIQUE,
    login         VARCHAR(120) NOT NULL,
    nome          VARCHAR(200) NOT NULL,
    email         VARCHAR(200),
    perfil        VARCHAR(20)  NOT NULL,
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    ultimo_acesso TIMESTAMP
);

-- Parâmetros gerais configuráveis (chave/valor)
CREATE TABLE parametro (
    chave     VARCHAR(60)    PRIMARY KEY,
    valor     NUMERIC(15, 4) NOT NULL,
    descricao VARCHAR(300)   NOT NULL,
    tipo      VARCHAR(20)    NOT NULL,
    ordem     INT            NOT NULL DEFAULT 0
);

CREATE TABLE faixa_comissao (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor_minimo NUMERIC(15, 2) NOT NULL,
    percentual   NUMERIC(7, 4)  NOT NULL
);

CREATE TABLE faixa_meta_semanal (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor_minimo NUMERIC(15, 2) NOT NULL,
    bonus        NUMERIC(15, 2) NOT NULL
);

CREATE TABLE forma_pagamento (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(80) NOT NULL UNIQUE,
    ativo BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE motivo_estorno (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(120) NOT NULL UNIQUE,
    ativo BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE produto_producao (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(120) NOT NULL UNIQUE,
    ativo BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE cliente (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(200) NOT NULL,
    razao_social VARCHAR(250),
    cnpj         VARCHAR(20),
    codigo       VARCHAR(40),
    conta        VARCHAR(40),
    telefone     VARCHAR(40),
    endereco     VARCHAR(250),
    numero       VARCHAR(20),
    bairro       VARCHAR(120),
    cidade       VARCHAR(120),
    uf           VARCHAR(2),
    cep          VARCHAR(10)
);
CREATE INDEX ix_cliente_nome ON cliente (nome);
CREATE INDEX ix_cliente_cnpj ON cliente (cnpj);

CREATE TABLE ordem_servico (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo               VARCHAR(40),
    vendedor_id          BIGINT         NOT NULL REFERENCES usuario (id),
    cliente_id           BIGINT         NOT NULL REFERENCES cliente (id),
    situacao             VARCHAR(20)    NOT NULL,
    data_emissao         DATE           NOT NULL,
    hora                 VARCHAR(5),
    previsao_entrega     DATE,
    servicos             TEXT,
    observacoes          TEXT,
    total_produtos       NUMERIC(15, 2) NOT NULL DEFAULT 0,
    total_servicos       NUMERIC(15, 2) NOT NULL DEFAULT 0,
    desconto             NUMERIC(15, 2) NOT NULL DEFAULT 0,
    total                NUMERIC(15, 2) NOT NULL,
    prazo_pagamento_dias INT,
    meia_margem          BOOLEAN        NOT NULL DEFAULT FALSE,
    documento_origem     VARCHAR(200),
    cancel_motivo        TEXT,
    cancel_data          DATE,
    estorno              BOOLEAN        NOT NULL DEFAULT FALSE,
    estorno_motivo_id    BIGINT REFERENCES motivo_estorno (id),
    estorno_valor        NUMERIC(15, 2),
    estorno_comprovante  VARCHAR(200),
    entregue             BOOLEAN        NOT NULL DEFAULT FALSE,
    data_entrega_real    DATE,
    criado_em            TIMESTAMP      NOT NULL,
    version              BIGINT         NOT NULL DEFAULT 0
);
CREATE INDEX ix_os_vendedor_emissao ON ordem_servico (vendedor_id, data_emissao);
CREATE INDEX ix_os_emissao ON ordem_servico (data_emissao);

CREATE TABLE item_os (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id          BIGINT         NOT NULL REFERENCES ordem_servico (id) ON DELETE CASCADE,
    tipo           VARCHAR(20)    NOT NULL,
    codigo         VARCHAR(40),
    descricao      VARCHAR(300)   NOT NULL,
    unidade        VARCHAR(10),
    quantidade     NUMERIC(15, 3) NOT NULL,
    valor_unitario NUMERIC(15, 2) NOT NULL,
    desconto       NUMERIC(15, 2) NOT NULL DEFAULT 0,
    valor_total    NUMERIC(15, 2) NOT NULL
);

CREATE TABLE parcela (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id            BIGINT         NOT NULL REFERENCES ordem_servico (id) ON DELETE CASCADE,
    numero           INT            NOT NULL,
    forma            VARCHAR(80)    NOT NULL,
    valor            NUMERIC(15, 2) NOT NULL,
    vencimento       DATE           NOT NULL,
    status           VARCHAR(20)    NOT NULL,
    data_recebimento DATE,
    comprovante      VARCHAR(200)
);
CREATE INDEX ix_parcela_vencimento ON parcela (vencimento, status);

-- Comissão por parcela: PENDENTE_RECEBIMENTO, PROVISORIA, AUTORIZADA, PAGA, CANCELADA
CREATE TABLE comissao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id         BIGINT         NOT NULL REFERENCES ordem_servico (id) ON DELETE CASCADE,
    parcela_id    BIGINT         NOT NULL UNIQUE REFERENCES parcela (id) ON DELETE CASCADE,
    vendedor_id   BIGINT         NOT NULL REFERENCES usuario (id),
    mes_ref       VARCHAR(7)     NOT NULL,
    base          NUMERIC(15, 2) NOT NULL,
    percentual    NUMERIC(7, 4)  NOT NULL,
    valor         NUMERIC(15, 2) NOT NULL,
    status        VARCHAR(25)    NOT NULL,
    autorizada_em TIMESTAMP,
    paga_em       TIMESTAMP
);
CREATE INDEX ix_comissao_status ON comissao (status, vendedor_id);
CREATE INDEX ix_comissao_mes ON comissao (mes_ref);

-- Fechamento mensal: trava a faixa (%) do vendedor no mês da venda
CREATE TABLE fechamento_mensal (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mes_ref             VARCHAR(7)     NOT NULL,
    vendedor_id         BIGINT         NOT NULL REFERENCES usuario (id),
    total_vendido       NUMERIC(15, 2) NOT NULL,
    faturamento_empresa NUMERIC(15, 2) NOT NULL,
    percentual          NUMERIC(7, 4)  NOT NULL,
    regra               VARCHAR(400),
    salario_fixo        NUMERIC(15, 2) NOT NULL,
    fechado_em          TIMESTAMP      NOT NULL,
    CONSTRAINT uk_fechamento UNIQUE (mes_ref, vendedor_id)
);

CREATE TABLE meta_semanal_paga (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendedor_id   BIGINT         NOT NULL REFERENCES usuario (id),
    semana_inicio DATE           NOT NULL,
    total         NUMERIC(15, 2) NOT NULL,
    bonus         NUMERIC(15, 2) NOT NULL,
    paga_em       TIMESTAMP      NOT NULL,
    CONSTRAINT uk_meta_semana UNIQUE (vendedor_id, semana_inicio)
);

CREATE TABLE bloqueio_calendario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data       DATE   NOT NULL,
    produto_id BIGINT NOT NULL REFERENCES produto_producao (id),
    observacao VARCHAR(300),
    CONSTRAINT uk_bloqueio UNIQUE (data, produto_id)
);

CREATE TABLE aviso (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo       VARCHAR(20) NOT NULL,
    texto      TEXT        NOT NULL,
    urgente    BOOLEAN     NOT NULL DEFAULT FALSE,
    os_id      BIGINT REFERENCES ordem_servico (id) ON DELETE SET NULL,
    produto_id BIGINT REFERENCES produto_producao (id),
    data       DATE,
    autor_id   BIGINT REFERENCES usuario (id),
    ativo      BOOLEAN     NOT NULL DEFAULT TRUE,
    criado_em  TIMESTAMP   NOT NULL
);

CREATE TABLE ocorrencia (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id        BIGINT      NOT NULL REFERENCES ordem_servico (id) ON DELETE CASCADE,
    tipo         VARCHAR(40) NOT NULL,
    descricao    TEXT        NOT NULL,
    status       VARCHAR(20) NOT NULL,
    usuario_id   BIGINT REFERENCES usuario (id),
    criado_em    TIMESTAMP   NOT NULL,
    resolvido_em TIMESTAMP
);

CREATE TABLE log_alteracao (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id      BIGINT,
    usuario_id BIGINT,
    acao       VARCHAR(40) NOT NULL,
    detalhe    TEXT,
    criado_em  TIMESTAMP   NOT NULL
);
CREATE INDEX ix_log_os ON log_alteracao (os_id);
